package ControlStatements.Iterative_Statement;

public class Whileloop_demo {
    public static void main(String[] ruby) {
        //Print Numbers from 1 to 10
        int x = 1;
        while (x <= 10) {
            System.out.print(x + " ");
            x++;
        }

        System.out.println();

        //Print numbers from 10 to 1
        int y = 10;
        while (y >= 1) {
            System.out.print(y + " ");
            y--;
        }

    }
    
}
