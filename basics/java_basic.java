/*
 * ==========================================================
 * 1. JAVA PROGRAM STRUCTURE
 * ==========================================================
 *
 * A basic Java program has:
 *
 * class
 * main() method
 * executable statements
 *
 *
 * Basic structure:
 *
 * public class ClassName {
 *
 *     public static void main(String[] args) {
 *
 *         // executable code
 *
 *     }
 * }
 *
 *
 * IMPORTANT:
 *
 * - Executable statements are written inside the main() method.
 * - main() is the starting point of a basic Java program.
 * - The class contains the main() method.
 */


public class java_basic {

    public static void main(String[] args) {

        // Executable code goes here.
        System.out.println("Hello Vishal");

    }
}